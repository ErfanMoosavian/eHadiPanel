  const Q_SVG = '<svg class="eh-help-svg" width="18" height="18" viewBox="0 0 24 24" fill="none" aria-hidden="true"><circle class="eh-help-ring" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="1.65"/><path d="M14.91 9a3 3 0 0 0-5.83 1c0 2 2.92 2.75 2.92 3.5" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/><circle cx="12" cy="17.25" r="1.15" fill="currentColor"/></svg>';
  let activePop = null;

  function closePopover() {
    if (activePop) {
      activePop.el.remove();
      activePop.btn?.classList.remove('active');
      activePop = null;
    }
  }

  function escHtml(s) {
    return String(s ?? '')
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  function openPopover(btn, topicKey) {
    const data = TOPICS[topicKey];
    if (!data) return;
    if (activePop && activePop.btn === btn) {
      closePopover();
      return;
    }
    closePopover();

    const pop = document.createElement('div');
    pop.className = 'eh-help-popover';
    pop.setAttribute('role', 'dialog');
    pop.setAttribute('aria-label', data.title);
    pop.innerHTML = `
      <div class="eh-help-pop-head">
        <div class="eh-help-pop-meta">
          <span class="eh-help-pop-cat">${escHtml(data.cat)}</span>
          <strong class="eh-help-pop-title">${escHtml(data.title)}</strong>
        </div>
        <button type="button" class="eh-help-pop-close" title="بستن">✕</button>
      </div>
      <div class="eh-help-pop-body">
        <p class="eh-help-pop-desc">${escHtml(data.desc)}</p>
        ${(data.items && data.items.length) ? `
          <ul class="eh-help-pop-list">
            ${data.items.map(([k, v]) => `<li><strong>${escHtml(k)}:</strong> <span>${escHtml(v)}</span></li>`).join('')}
          </ul>
        ` : ''}
        ${data.tip ? `<div class="eh-help-pop-tip"><strong>نکته کاربردی:</strong> ${escHtml(data.tip)}</div>` : ''}
      </div>
    `;

    pop.addEventListener('click', (e) => e.stopPropagation());
    pop.querySelector('.eh-help-pop-close').addEventListener('click', closePopover);
    document.body.appendChild(pop);

    const r = btn.getBoundingClientRect();
    const popW = Math.min(365, window.innerWidth - 24);
    pop.style.width = `${popW}px`;
    const popH = pop.offsetHeight || 240;

    let top = r.bottom + 8;
    if (top + popH > window.innerHeight - 12) {
      top = Math.max(12, r.top - popH - 8);
    }
    let left = r.right - popW;
    if (left < 12) left = Math.min(window.innerWidth - popW - 12, r.left);
    if (left + popW > window.innerWidth - 12) left = window.innerWidth - popW - 12;

    pop.style.top = `${Math.round(top)}px`;
    pop.style.left = `${Math.round(Math.max(12, left))}px`;
    btn.classList.add('active');
    requestAnimationFrame(() => pop.classList.add('open'));
    activePop = { el: pop, btn, key: topicKey };
  }

  function btnHtml(topicKey, extraClass = '') {
    if (!TOPICS[topicKey]) return '';
    return `<button type="button" class="eh-help-btn ${extraClass}" data-eh-help="${topicKey}" title="راهنمای این بخش" aria-label="راهنمای این بخش">${Q_SVG}</button>`;
  }

  document.addEventListener('click', (e) => {
    const hb = e.target && e.target.closest ? e.target.closest('[data-eh-help]') : null;
    if (hb) {
      e.preventDefault();
      e.stopPropagation();
      openPopover(hb, hb.getAttribute('data-eh-help'));
      return;
    }
    if (activePop && !activePop.el.contains(e.target)) {
      closePopover();
    }
  });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closePopover(); });
  window.addEventListener('resize', closePopover);
  window.addEventListener('scroll', (e) => {
    if (activePop && activePop.el && (e.target === activePop.el || activePop.el.contains(e.target))) return;
    closePopover();
  }, true);

