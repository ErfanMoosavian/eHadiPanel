"""
مدیریت هوشمند فونت‌های فارسی eHadiPanel (نسخه v48.0 Pro)
- هنگام اجرای برنامه روی هر لپ‌تاپ جدید، فونت‌های موجود در پوشه src/ui/web/fonts را
  به‌صورت خودکار (در صورت نبودن روی ویندوز) بدون نیاز به دسترسی Admin نصب و ثبت می‌کند.
- فایل fonts.css را با @font-face محلی همگام نگه می‌دارد تا نمایش متن و اعداد روی
  تمام سیستم‌ها (حتی آفلاین) ۱۰۰٪ یکسان با سیستم اصلی باشد.
"""
from __future__ import annotations

import logging
import os
import re
import shutil
import sys
from pathlib import Path
from typing import Any

logger = logging.getLogger("eHadiPanel.Fonts")

FONT_EXTS = {".ttf", ".otf", ".woff2", ".woff"}
WIN_INSTALLABLE_EXTS = {".ttf", ".otf"}

PREFERRED_PREFIXES = (
    "vazirmatn",
    "vazir",
    "iransans",
    "yekanbakh",
    "dana",
    "shabnam",
    "estedad",
    "sahel",
    "b nazanin",
    "bnazanin",
)


def _project_root() -> Path:
    if getattr(sys, "frozen", False):
        return Path(getattr(sys, "_MEIPASS", Path(sys.executable).resolve().parent))
    return Path(__file__).resolve().parents[2]


def get_fonts_dir() -> Path:
    root = _project_root()
    candidates = [
        root / "src" / "ui" / "web" / "fonts",
        Path(__file__).resolve().parents[1] / "ui" / "web" / "fonts",
    ]
    for c in candidates:
        if c.exists():
            return c
    d = candidates[0]
    d.mkdir(parents=True, exist_ok=True)
    return d


def _guess_weight(filename: str) -> int:
    s = filename.lower()
    if "black" in s or "900" in s:
        return 900
    if "extrabold" in s or "800" in s:
        return 800
    if "bold" in s or "700" in s:
        return 700
    if "semibold" in s or "demibold" in s or "600" in s:
        return 600
    if "medium" in s or "500" in s:
        return 500
    if "light" in s or "300" in s:
        return 300
    if "thin" in s or "100" in s:
        return 100
    return 400


def _is_variable_font(filename: str) -> bool:
    s = filename.lower()
    return "[wght]" in s or "variable" in s or "vf" in re.split(r"[-_.\s]+", s)


def _font_format(ext: str) -> str:
    return {
        ".woff2": "woff2",
        ".woff": "woff",
        ".ttf": "truetype",
        ".otf": "opentype",
    }.get(ext.lower(), "truetype")


def generate_fonts_css(fonts_dir: Path | None = None) -> Path:
    """Generates local @font-face CSS from bundled font files inside src/ui/web/fonts."""
    fdir = fonts_dir or get_fonts_dir()
    fdir.mkdir(parents=True, exist_ok=True)
    css_path = fdir / "fonts.css"

    files = sorted(
        [p for p in fdir.iterdir() if p.is_file() and p.suffix.lower() in FONT_EXTS],
        key=lambda p: (0 if p.suffix.lower() == ".woff2" else 1, p.name.lower()),
    )

    if not files:
        css_path.write_text(
            "/* فونت محلی در پوشه src/ui/web/fonts قرار داده نشده است.\n"
            "   برای بسته‌بندی خودکار فونت‌های سیستم خودتان دستور زیر را اجرا کنید:\n"
            "   python tools/collect_fonts.py */\n",
            encoding="utf-8",
        )
        return css_path

    blocks: list[str] = [
        "/* Auto-generated by eHadiPanel Font Manager (v48.0 Pro) — Offline Embedded Fonts */"
    ]
    for fp in files:
        fmt = _font_format(fp.suffix)
        weight_rule = "100 900" if _is_variable_font(fp.name) else str(_guess_weight(fp.name))
        safe_url = fp.name.replace("'", "\\'")
        blocks.append(
            f"@font-face {{\n"
            f"  font-family: 'eHadiUI';\n"
            f"  src: url('{safe_url}') format('{fmt}');\n"
            f"  font-weight: {weight_rule};\n"
            f"  font-style: normal;\n"
            f"  font-display: swap;\n"
            f"}}"
        )

    blocks.append(
        "html, body, button, input, select, textarea {\n"
        "  font-family: 'eHadiUI', 'Vazirmatn', 'Vazirmatn FD', 'IRANSansX', 'IRANSans', 'Yekan Bakh', 'Segoe UI', Tahoma, sans-serif !important;\n"
        "}\n"
        ".pro-kbd, code, pre, .eh-diag-err-txt {\n"
        "  font-family: 'eHadiUI', Consolas, 'Vazirmatn', monospace !important;\n"
        "}\n"
    )
    css_path.write_text("\n\n".join(blocks), encoding="utf-8")
    return css_path


def _windows_font_installed(font_filename: str) -> bool:
    sys_fonts = Path(os.environ.get("WINDIR", r"C:\Windows")) / "Fonts"
    user_fonts = Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "Windows" / "Fonts"
    low = font_filename.lower()
    for folder in (sys_fonts, user_fonts):
        if folder.exists():
            try:
                if (folder / font_filename).exists():
                    return True
                for item in folder.iterdir():
                    if item.name.lower() == low:
                        return True
            except Exception:
                pass
    return False


def ensure_fonts_installed_on_windows(fonts_dir: Path | None = None) -> dict[str, Any]:
    """
    Installs bundled .ttf/.otf fonts into the current Windows user's Fonts folder
    if they are missing on this laptop (no Admin elevation needed) and notifies GDI/WebView2.
    """
    fdir = fonts_dir or get_fonts_dir()
    result: dict[str, Any] = {"ok": True, "installed": [], "skipped": [], "errors": []}

    try:
        generate_fonts_css(fdir)
    except Exception as exc:
        result["errors"].append(f"css: {exc}")

    if os.name != "nt" or not fdir.exists():
        return result

    installable = [p for p in fdir.iterdir() if p.is_file() and p.suffix.lower() in WIN_INSTALLABLE_EXTS]
    if not installable:
        return result

    user_fonts = Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "Windows" / "Fonts"
    try:
        user_fonts.mkdir(parents=True, exist_ok=True)
    except Exception as exc:
        result["errors"].append(f"mkdir: {exc}")
        return result

    changed = False
    try:
        import ctypes
        import winreg  # type: ignore

        gdi32 = ctypes.windll.gdi32
        user32 = ctypes.windll.user32
        reg_path = r"Software\Microsoft\Windows NT\CurrentVersion\Fonts"

        for fp in installable:
            if _windows_font_installed(fp.name):
                result["skipped"].append(fp.name)
                continue
            dest = user_fonts / fp.name
            try:
                shutil.copy2(fp, dest)
                font_label = f"{fp.stem} ({'OpenType' if fp.suffix.lower() == '.otf' else 'TrueType'})"
                with winreg.CreateKey(winreg.HKEY_CURRENT_USER, reg_path) as key:
                    winreg.SetValueEx(key, font_label, 0, winreg.REG_SZ, str(dest))
                gdi32.AddFontResourceW(str(dest))
                result["installed"].append(fp.name)
                changed = True
            except Exception as exc:
                result["errors"].append(f"{fp.name}: {exc}")

        if changed:
            HWND_BROADCAST = 0xFFFF
            WM_FONTCHANGE = 0x001D
            SMTO_ABORTIFHUNG = 0x0002
            try:
                user32.SendMessageTimeoutW(HWND_BROADCAST, WM_FONTCHANGE, 0, 0, SMTO_ABORTIFHUNG, 1000, None)
            except Exception:
                pass
    except Exception as exc:
        result["ok"] = False
        result["errors"].append(str(exc))

    if result["installed"]:
        logger.info("Auto-installed bundled fonts for Windows user: %s", ", ".join(result["installed"]))
    return result
