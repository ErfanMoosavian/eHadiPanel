"""
اسکریپت جمع‌آوری خودکار فونت فارسی از ویندوز شما برای بسته‌بندی در نسخه Setup
نحوه اجرا در پوشه پروژه:
    python tools/collect_fonts.py
یا با نام فونت دلخواه:
    python tools/collect_fonts.py Vazirmatn
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.core.font_manager import PREFERRED_PREFIXES, generate_fonts_css

FONTS_DEST = ROOT / "src" / "ui" / "web" / "fonts"
ISS_PATH = ROOT / "installer" / "eHadiPanel_Fonts.iss"


def find_windows_fonts(preferred: str = "") -> list[Path]:
    dirs = [
        Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "Windows" / "Fonts",
        Path(os.environ.get("WINDIR", r"C:\Windows")) / "Fonts",
    ]
    all_fonts: list[Path] = []
    for d in dirs:
        if d.exists():
            for fp in d.iterdir():
                if fp.is_file() and fp.suffix.lower() in {".ttf", ".otf"}:
                    all_fonts.append(fp)

    if preferred:
        q = preferred.lower().strip()
        return sorted([f for f in all_fonts if q in f.name.lower()], key=lambda x: x.name.lower())

    # Pick the highest-priority installed Persian UI family automatically
    for pref in PREFERRED_PREFIXES:
        matches = [f for f in all_fonts if pref in f.name.lower()]
        if matches:
            # Prefer FD / FaNum variants if available
            fd_matches = [m for m in matches if any(tag in m.name.lower() for tag in ("fd", "fanum", "farsi"))]
            chosen = fd_matches or matches
            # Keep variable font OR standard weights (Regular, Medium, SemiBold, Bold, ExtraBold)
            var_fonts = [m for m in chosen if "[wght]" in m.name.lower() or "variable" in m.name.lower()]
            if var_fonts:
                return var_fonts[:2]
            keep_weights = ("regular", "medium", "semibold", "bold", "extrabold", "light")
            weighted = [m for m in chosen if any(w in m.name.lower() for w in keep_weights)]
            return sorted(weighted or chosen, key=lambda x: x.name.lower())[:6]
    return []


def write_inno_snippet(bundled: list[Path]) -> None:
    ISS_PATH.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "; Auto-generated by tools/collect_fonts.py — Inno Setup Font Auto-Installer",
        "; این فایل را با دستور زیر داخل بخش [Files] اسکریپت Inno Setup خود اضافه کنید:",
        '; #include "installer\\eHadiPanel_Fonts.iss"',
        "",
    ]
    for fp in bundled:
        title = f"{fp.stem} ({'OpenType' if fp.suffix.lower() == '.otf' else 'TrueType'})"
        lines.append(
            f'Source: "src\\ui\\web\\fonts\\{fp.name}"; DestDir: "{{autofonts}}"; '
            f'FontInstall: "{title}"; Flags: onlyifdoesntexist uninsneveruninstall'
        )
    if not bundled:
        lines.append("; هنوز فونتی در src\\ui\\web\\fonts جمع‌آوری نشده است.")
    ISS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    pref = sys.argv[1] if len(sys.argv) > 1 else ""
    found = find_windows_fonts(pref)
    FONTS_DEST.mkdir(parents=True, exist_ok=True)

    if not found:
        print("فونت فارسی استاندارد (مثل Vazirmatn یا IRANSans) در پوشه Fonts ویندوز پیدا نشد.")
        print("می‌توانید فایل .ttf فونت دلخواه خود را دستی داخل پوشه زیر کپی کرده و دوباره اجرا کنید:")
        print(f"  {FONTS_DEST}")
        generate_fonts_css(FONTS_DEST)
        write_inno_snippet([p for p in FONTS_DEST.iterdir() if p.suffix.lower() in {".ttf", ".otf"}])
        return

    # Clear old collected ttf/otf before copying new matched family
    for old in FONTS_DEST.iterdir():
        if old.is_file() and old.suffix.lower() in {".ttf", ".otf"}:
            old.unlink()

    copied: list[Path] = []
    for src in found:
        dst = FONTS_DEST / src.name
        shutil.copy2(src, dst)
        copied.append(dst)
        print(f"  [+] کپی شد: {src.name}")

    css_p = generate_fonts_css(FONTS_DEST)
    write_inno_snippet(copied)
    print(f"\nانجام شد! {len(copied)} فایل فونت داخل برنامه بسته‌بندی شد:")
    print(f"  - CSS محلی: {css_p}")
    print(f"  - اسکریپت نصب خودکار Setup (Inno Setup): {ISS_PATH}")


if __name__ == "__main__":
    main()
